import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { SaleRecord, BrandMetricSummary, AdsMetricsSummary } from '../types';

interface GeneratePdfOptions {
  userEmail: string;
  brandMetrics: BrandMetricSummary[];
  adsMetrics: AdsMetricsSummary;
  records: SaleRecord[];
  activeBrandFilter?: string;
  dateRangeStr?: string;
}

export function generatePdfReport(options: GeneratePdfOptions) {
  const { userEmail, brandMetrics, adsMetrics, records, activeBrandFilter, dateRangeStr } = options;
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const totalGmv = records.reduce((acc, r) => acc + r.gmv, 0);
  const totalUnits = records.reduce((acc, r) => acc + r.unitsSold, 0);
  const totalOrders = records.length;
  const asp = totalUnits > 0 ? totalGmv / totalUnits : 0;
  const aov = totalOrders > 0 ? totalGmv / totalOrders : 0;

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, 595.28, 90, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.text('IM02 ANALYTICS SUITE', 40, 42);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(148, 163, 184); // slate-400
  doc.text('Executive Sales, Brand Intelligence & Marketing Ads Report', 40, 62);

  // Meta Info Box
  doc.setTextColor(51, 65, 85); // slate-700
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text('REPORT DETAILS & ATTRIBUTION:', 40, 115);

  doc.setFont('helvetica', 'normal');
  doc.text(`Generated By (Email): ${userEmail || 'mdmanir179@gmail.com'}`, 40, 130);
  doc.text(`Date & Time: ${new Date().toLocaleString()}`, 40, 144);
  doc.text(`Active Scope: ${activeBrandFilter ? `Brand: ${activeBrandFilter.toUpperCase()}` : 'All Brands'} | ${dateRangeStr || 'Complete Period'}`, 40, 158);

  // Summary KPI Cards in PDF
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(40, 175, 120, 50, 4, 4, 'F');
  doc.roundedRect(170, 175, 120, 50, 4, 4, 'F');
  doc.roundedRect(300, 175, 120, 50, 4, 4, 'F');
  doc.roundedRect(430, 175, 125, 50, 4, 4, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('TOTAL GMV', 50, 192);
  doc.text('UNITS SOLD', 180, 192);
  doc.text('AVG ORDER VAL (AOV)', 310, 192);
  doc.text('AVG SELLING PRICE (ASP)', 440, 192);

  doc.setFontSize(13);
  doc.setTextColor(15, 23, 42);
  doc.text(`INR ${Math.round(totalGmv).toLocaleString()}`, 50, 212);
  doc.text(`${totalUnits.toLocaleString()} pcs`, 180, 212);
  doc.text(`INR ${Math.round(aov).toLocaleString()}`, 310, 212);
  doc.text(`INR ${Math.round(asp).toLocaleString()}`, 440, 212);

  // Section 1: Brand Metrics Table
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('1. Brand Metrics & Comparative Performance', 40, 250);

  const brandRows = brandMetrics.map((b) => [
    b.brand.toUpperCase(),
    `INR ${Math.round(b.totalGMV).toLocaleString()}`,
    `${((b.totalGMV / (totalGmv || 1)) * 100).toFixed(1)}%`,
    `${b.totalUnits} units`,
    `INR ${Math.round(b.asp)}`,
    `INR ${Math.round(b.aov)}`,
    `${b.comboShare.toFixed(1)}%`,
    b.topCity.toUpperCase()
  ]);

  autoTable(doc, {
    startY: 260,
    head: [['Brand', 'GMV', 'Share %', 'Volume', 'ASP', 'AOV', 'Combo %', 'Top City']],
    body: brandRows,
    theme: 'grid',
    headStyles: { fillColor: [79, 70, 229], textColor: [255, 255, 255], fontStyle: 'bold' },
    styles: { fontSize: 8, cellPadding: 5 },
    margin: { left: 40, right: 40 }
  });

  // Section 2: Ads & Marketing Performance Table
  const lastY1 = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY || 330;
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('2. Advertising & Campaign ROI Metrics', 40, lastY1 + 25);

  const adsRows = [
    ['Total Ad Spend', `INR ${Math.round(adsMetrics.totalSpend).toLocaleString()}`, 'ROAS (Ad GMV / Spend)', `${adsMetrics.roas.toFixed(2)}x`],
    ['Ad Attributed GMV', `INR ${Math.round(adsMetrics.adGmv).toLocaleString()}`, 'ACoS (Spend / Ad GMV)', `${adsMetrics.acos.toFixed(1)}%`],
    ['Organic GMV', `INR ${Math.round(adsMetrics.organicGmv).toLocaleString()}`, 'TACoS (Spend / Total GMV)', `${adsMetrics.tacos.toFixed(1)}%`],
    ['Ad Impressions', adsMetrics.impressions.toLocaleString(), 'CTR (Click-Through Rate)', `${adsMetrics.ctr.toFixed(2)}%`],
    ['Ad Clicks', adsMetrics.clicks.toLocaleString(), 'Avg CPC (Cost Per Click)', `INR ${adsMetrics.cpc.toFixed(2)}`],
    ['Ad Conversion Rate (CVR)', `${adsMetrics.cvr.toFixed(2)}%`, 'Blended ROAS (Total GMV / Spend)', `${adsMetrics.blendedRoas.toFixed(2)}x`]
  ];

  autoTable(doc, {
    startY: lastY1 + 35,
    head: [['Metric', 'Value', 'ROI / Efficiency Metric', 'Calculated Ratio']],
    body: adsRows,
    theme: 'striped',
    headStyles: { fillColor: [14, 165, 233], textColor: [255, 255, 255], fontStyle: 'bold' },
    styles: { fontSize: 8, cellPadding: 5 },
    margin: { left: 40, right: 40 }
  });

  // Section 3: Top Products Breakdown
  const lastY2 = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY || 470;
  
  // Check if we need page break
  if (lastY2 > 650) {
    doc.addPage();
  }

  const startY3 = lastY2 > 650 ? 50 : lastY2 + 25;
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('3. Top Products by Sales Volume & GMV Contribution', 40, startY3);

  // Group by product
  const productMap = new Map<string, { brand: string; sku: string; units: number; gmv: number; mrp: number }>();
  records.forEach((r) => {
    const key = r.productName;
    const existing = productMap.get(key) || { brand: r.brand, sku: r.itemCode, units: 0, gmv: 0, mrp: r.baseMrp };
    existing.units += r.unitsSold;
    existing.gmv += r.gmv;
    productMap.set(key, existing);
  });

  const sortedProducts = Array.from(productMap.entries())
    .sort((a, b) => b[1].gmv - a[1].gmv)
    .slice(0, 10);

  const productRows = sortedProducts.map(([name, data]) => [
    data.brand.toUpperCase(),
    name,
    data.sku,
    `${data.units} pcs`,
    `INR ${Math.round(data.gmv).toLocaleString()}`,
    `${((data.gmv / (totalGmv || 1)) * 100).toFixed(1)}%`
  ]);

  autoTable(doc, {
    startY: startY3 + 10,
    head: [['Brand', 'Product Name', 'SKU', 'Units Sold', 'Total GMV', 'Revenue Share']],
    body: productRows,
    theme: 'grid',
    headStyles: { fillColor: [16, 185, 129], textColor: [255, 255, 255], fontStyle: 'bold' },
    styles: { fontSize: 8, cellPadding: 4 },
    columnStyles: {
      1: { cellWidth: 220 }
    },
    margin: { left: 40, right: 40 }
  });

  // Footer on each page
  const pageCount = (doc as unknown as { internal: { getNumberOfPages: () => number } }).internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`IM02 Analytics Platform | Confidential Sales Report | Reporter: ${userEmail || 'mdmanir179@gmail.com'}`, 40, 820);
    doc.text(`Page ${i} of ${pageCount}`, 520, 820);
  }

  // Trigger download
  const dateTag = new Date().toISOString().split('T')[0];
  doc.save(`IM02_Sales_Report_${dateTag}.pdf`);
}
